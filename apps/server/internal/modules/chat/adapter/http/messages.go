package httpadapter

import (
	"context"
	"net/http"

	"github.com/KPV2004/samnak-chat/apps/server/internal/modules/chat/adapter/wire"
	"github.com/KPV2004/samnak-chat/apps/server/internal/modules/chat/usecase"
)

type listMessagesInput struct {
	ID           string `path:"id"`
	AfterSeq     int64  `query:"after_seq" default:"-1" minimum:"-1" maximum:"9007199254740991" doc:"Catch-up: messages with a larger seq, ascending. -1 (the default) means not set"`
	BeforeSeq    int64  `query:"before_seq" default:"0" minimum:"0" maximum:"9007199254740991" doc:"History: messages with a smaller seq. 0 (the default) means the newest messages"`
	Limit        int    `query:"limit" default:"50" minimum:"1" maximum:"100"`
	ThreadRootID string `query:"thread_root_id" maxLength:"36" doc:"Only the replies to this message"`
}

type listMessagesOutput struct {
	Body struct {
		Items   []wire.Message `json:"items" nullable:"false" doc:"Ascending by seq; replies are included"`
		HasMore bool           `json:"has_more" doc:"More messages exist in the direction of the query"`
	}
}

func (h *Handler) listMessages(ctx context.Context, in *listMessagesInput) (*listMessagesOutput, error) {
	p, err := principal(ctx)
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	q := usecase.ListQuery{BeforeSeq: in.BeforeSeq, Limit: in.Limit, ThreadRootID: in.ThreadRootID}
	if in.AfterSeq >= 0 {
		q.AfterSeq = &in.AfterSeq
	}
	page, err := h.uc.ListMessages(ctx, p, in.ID, q)
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	out := &listMessagesOutput{}
	out.Body.HasMore = page.HasMore
	out.Body.Items = make([]wire.Message, len(page.Items))
	for i, m := range page.Items {
		out.Body.Items[i] = wire.ToMessage(m, p.UserID)
	}
	return out, nil
}

type messageOutput struct {
	Status int
	Body   wire.Message
}

type sendMessageInput struct {
	ID   string `path:"id"`
	Body struct {
		ClientMsgID   string   `json:"client_msg_id" format:"uuid" doc:"Generated by the client; sending it again never creates a second message"`
		Body          string   `json:"body" maxLength:"4000" doc:"Markdown, 1 to 4,000 characters; may be empty when attachment_ids is not. Mention people with <@user_id> and everyone with <!channel>"`
		ThreadRootID  string   `json:"thread_root_id,omitempty" maxLength:"36" doc:"Reply under this top-level message"`
		AttachmentIDs []string `json:"attachment_ids,omitempty" maxItems:"10" maxLength:"36" doc:"Files from POST /chat/uploads that you uploaded to this channel; each can be used once"`
	}
}

func (h *Handler) sendMessage(ctx context.Context, in *sendMessageInput) (*messageOutput, error) {
	p, err := principal(ctx)
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	v, created, err := h.uc.SendMessage(ctx, p, usecase.SendInput{
		ChannelID: in.ID, ClientMsgID: in.Body.ClientMsgID, Body: in.Body.Body, ThreadRootID: in.Body.ThreadRootID, AttachmentIDs: in.Body.AttachmentIDs,
	})
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	status := http.StatusOK
	if created {
		status = http.StatusCreated
	}
	return &messageOutput{Status: status, Body: wire.ToMessage(v, p.UserID)}, nil
}

type editMessageInput struct {
	ID   string `path:"id"`
	Body struct {
		Body string `json:"body" minLength:"1" maxLength:"4000"`
	}
}

func (h *Handler) editMessage(ctx context.Context, in *editMessageInput) (*messageOutput, error) {
	p, err := principal(ctx)
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	v, err := h.uc.EditMessage(ctx, p, in.ID, in.Body.Body)
	if err != nil {
		return nil, h.fail(ctx, err)
	}
	return &messageOutput{Status: http.StatusOK, Body: wire.ToMessage(v, p.UserID)}, nil
}

